export function generateProceduralBounty(playerLevel = 1): QuestItem {
  const bountyNpcs = [
    { name: '洛中捕快・服部', avatar: '👮' },
    { name: '東海道飛腳・彌七', avatar: '🏃' },
    { name: '出雲行腳巫女', avatar: '🌸' },
    { name: '茶屋看板娘・小町', avatar: '🍡' },
    { name: '鍛造學徒・小鐵', avatar: '🔨' }
  ];
  const monsterNames = ['貪吃赤面鬼', '惡作劇天狗', '迷路傘妖', '偷酒化狸', '愛玩提燈妖', '翹班河童'];
  const zones = ['京都・洛中城下町', '鞍馬山・天狗靈峰', '東海道・荒涼驛道', '富士山麓・赤富士戰場', '日光・輪王神域'];
  const npc = bountyNpcs[Math.floor(Math.random() * bountyNpcs.length)];
  const monster = monsterNames[Math.floor(Math.random() * monsterNames.length)];
  const zone = zones[Math.floor(Math.random() * zones.length)];
  const kills = 12 + Math.floor(Math.random() * 16);
  const powerReq = Math.round((playerLevel * 65 + 100) * (0.9 + Math.random() * 0.3));

  const gold = Math.round(playerLevel * 120 + 200 + Math.random() * 300);
  const iron = Math.round(playerLevel * 5 + 15 + Math.random() * 10);
  const souls = Math.round(playerLevel * 1.5 + 2);
  const exp = Math.round(playerLevel * 180 + 300);

  return {
    id: 'bounty_' + Date.now() + '_' + Math.random().toString(36).slice(2, 6),
    type: 'bounty',
    title: `街坊委託：驅趕【${monster}】`,
    npc: npc.name,
    npcAvatar: npc.avatar,
    dialogue: `「聽說有群 ${monster} 在 ${zone} 附近喧嘩偷吃點心！請幫忙教訓 ${kills} 隻，街坊們準備了豐厚謝禮！」`,
    lore: `天明七年城下町與宿場町居民張貼在茶屋布告欄上的日常互助委託。`,
    targetKills: kills,
    zone,
    recommendedPower: powerReq,
    rewards: { exp, gold, iron, souls }
  };
}
